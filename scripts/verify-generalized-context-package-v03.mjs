import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { buildDecisionMemoryLedger } from "../experience/context-v02/decision-memory-ledger.mjs";
import { buildContextPackageV02 } from "../experience/context-v02/context-package-projector.mjs";
import { buildGeneralizedContextPackage, adaptGeneralizedContextPackageToV02 } from "../experience/context-v03/generalized-context-package-builder.mjs";

const graph = JSON.parse(await readFile(new URL("../examples/nexus-atlas-self-context-v0.2.json", import.meta.url), "utf8"));
const generatedAt = "2026-08-05T09:00:00+08:00";
const options = { graph, projectId: "project:nexus-atlas", scopeKey: "project:nexus-atlas", generatedAt };
const ledger = buildDecisionMemoryLedger(options);
const packageV03 = buildGeneralizedContextPackage({ ...options, ledger });
const legacy = adaptGeneralizedContextPackageToV02(packageV03);
const existing = buildContextPackageV02({ graph, generatedAt, decisionMemoryLedger: ledger });
const providerTotal = Object.values(packageV03.sourceSummary.providers).reduce((sum, value) => sum + value, 0);
const kindTotal = Object.values(packageV03.sourceSummary.byKind).reduce((sum, value) => sum + value, 0);
const declarations = graph.contextPackage.omittedContext.map((item) => item.item);

assert.equal(packageV03.packageVersion, "0.3");
assert.equal(packageV03.packageId, "context-package:project-nexus-atlas:2026-08-05T09-00-00-08-00");
assert.equal(packageV03.sourceSummary.totalIncludedRecords, 24);
assert.equal(providerTotal, 24);
assert.equal(kindTotal, 24);
assert.equal(packageV03.decisions.effective.length, 6);
assert.equal(packageV03.decisions.proposed.length, 0);
assert.equal(packageV03.decisions.chains.length, 6);
assert.equal(packageV03.memories.inherited.length, 3);
assert.equal(packageV03.memories.inferred.length, 1);
assert.equal(packageV03.memories.disputed.length, 0);
assert.equal(packageV03.memories.historical.length, 1);
assert.equal(packageV03.evidence.current.length, 5);
assert.equal(packageV03.risks.open.length, 5);
assert.equal(packageV03.actions.next.length, 1);
assert.equal(packageV03.conflicts.unresolved.length, 0);
assert.ok(packageV03.decisions.chains.some((chain) => chain.orderedDecisionIds.includes("decision:connectors-first")));
assert.deepEqual(packageV03.omissions.map((item) => item.item), declarations);
assert.equal(legacy.packageVersion, "0.2");
assert.equal(legacy.packageId, "context-package:nexus-atlas:2026-08-05T09-00-00-08-00");
assert.equal(legacy.sourceSummary.totalIncludedNodes, 19);
assert.equal(legacy.confirmedDecisions.length, 6);
assert.equal(legacy.currentEvidence.length, 5);
assert.equal(legacy.staleContext.length, 1);
assert.equal(legacy.openRisks.length, 5);
assert.equal(legacy.nextActions.length, 1);
assert.deepEqual(legacy, existing);

